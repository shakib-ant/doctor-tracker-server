export const seed50Doctors = async () => {
  try {
    console.log("Connecting to MongoDB Atlas...");
    await mongoose.connect(process.env.MONGO_URI, { serverSelectionTimeoutMS: 8000 });
    console.log("Connected to MongoDB Atlas successfully.");

    // Preserve existing records and prevent duplicates by email
    const initialCount = await Doctor.countDocuments();
    console.log(`Initial Doctor count in database: ${initialCount}`);

    let insertedCount = 0;
    let skippedCount = 0;

    for (const doc of synthetic50Doctors) {
      const exists = await Doctor.findOne({ email: doc.email.toLowerCase() });
      if (exists) {
        skippedCount++;
      } else {
        await Doctor.create(doc);
        insertedCount++;
      }
    }

    console.log(`Inserted ${insertedCount} new synthetic doctor profiles.`);
    console.log(`Skipped ${skippedCount} already-existing doctor profiles (idempotent).`);

    // Verify database read-back
    const totalCount = await Doctor.countDocuments();
    console.log(`Total Doctor count after seeding: ${totalCount}`);

    const sample = await Doctor.find({ about: { $regex: /Synthetic demo doctor/i } })
      .limit(3)
      .select("name specialization hospital consultationFee");
    console.log("Verified sample read-back:", sample);

    await mongoose.disconnect();
    return {
      success: true,
      initialCount,
      insertedCount,
      skippedCount,
      totalCount,
    };
  } catch (error) {
    console.error("Seed 50 Doctors execution error:", error.message);
    if (mongoose.connection.readyState !== 0) {
      await mongoose.disconnect();
    }
    return {
      success: false,
      error: error.message,
    };
  }
};

// Auto-run if executed directly
if (process.argv[1]?.endsWith("seed50Doctors.js")) {
  seed50Doctors().then((res) => {
    if (!res.success) process.exit(1);
    process.exit(0);
  });
}
